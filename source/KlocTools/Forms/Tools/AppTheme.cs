namespace Klocman.Forms.Tools
{
    /// <summary>
    ///     Color theme of the application windows.
    /// </summary>
    public enum AppTheme
    {
        /// <summary>
        ///     Standard light (white) Windows look.
        /// </summary>
        Light = 0,

        /// <summary>
        ///     Dark backgrounds with light text.
        /// </summary>
        Dark = 1,

        /// <summary>
        ///     Follow the "Choose your app mode" setting of Windows.
        /// </summary>
        System = 2
    }
}
